#!/usr/bin/env bash
set -Eeuo pipefail

# Start the services on the GPU server. Run this file as the deployment user
# (normally roger), because the LLM units belong to that user's systemd.

APP_DIR=${APP_DIR:-$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)}
ASR_ENV=${ASR_ENV:-/etc/sts-ws-server/asr.env}
WSS_ENV=${WSS_ENV:-"$APP_DIR/wss.env"}
SERVICE_USER=${SERVICE_USER:-$(id -un)}
SERVICE_GROUP=${SERVICE_GROUP:-$(id -gn)}
KEY_FILE=${KEY_FILE:-"$APP_DIR/.wss_api_key"}

SYSTEM_UNITS=(qwen3-tts-vllm.service sts-ws-qwen.service asr-ws.service kokoro-ws.service)
USER_UNITS=(llama-server.service llm-wss.service)

usage() {
    cat <<'EOF'
Usage: ./start.sh [options]

Configure the shared WSS_API_KEY and start the remote services.

Options:
  --key VALUE       use this WSS key (prefer WSS_API_KEY=VALUE in the environment)
  --key-file PATH   read/write the key from PATH (default: .wss_api_key)
  --rotate-key      generate a new 64-hex-character key
  --status          show service status without changing files or starting units
  --dry-run         show the planned actions without changing files or starting units
  -h, --help        show this help

Environment overrides:
  APP_DIR, ASR_ENV, WSS_ENV, SERVICE_USER, SERVICE_GROUP, KEY_FILE

The public gateway remains at wss://47.87.138.166:18443. This script starts
the model adapters and the Ornith bridge; it does not recreate the existing
Docker/Nginx gateway.
EOF
}

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

log() {
    printf '[start] %s\n' "$*"
}

have_command() {
    command -v "$1" >/dev/null 2>&1
}

run_root() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    else
        sudo "$@"
    fi
}

run_user_systemctl() {
    if [ "$(id -un)" = "$SERVICE_USER" ]; then
        systemctl --user "$@"
    else
        runuser -u "$SERVICE_USER" -- systemctl --user "$@"
    fi
}

read_existing_key() {
    local file value
    for file in "$WSS_ENV" "$ASR_ENV"; do
        value=''
        if [ -r "$file" ]; then
            value=$(awk -F= '$1 == "WSS_API_KEY" { print substr($0, index($0, "=") + 1); exit }' "$file")
        elif [ "$(id -u)" -eq 0 ] || have_command sudo; then
            value=$(run_root awk -F= '$1 == "WSS_API_KEY" { print substr($0, index($0, "=") + 1); exit }' "$file" 2>/dev/null || true)
        fi
        if [ -n "$value" ]; then
            printf '%s' "$value"
            return 0
        fi
    done
    if [ -r "$KEY_FILE" ]; then
        awk 'NF { print $1; exit }' "$KEY_FILE"
    fi
}

generate_key() {
    if have_command openssl; then
        openssl rand -hex 32
    elif have_command python3; then
        python3 -c 'import secrets; print(secrets.token_hex(32))'
    else
        die 'openssl or python3 is required to generate WSS_API_KEY'
    fi
}

validate_key() {
    local value=$1
    [ "${#value}" -ge 32 ] || die 'WSS_API_KEY must contain at least 32 characters'
    [[ "$value" != *$'\n'* && "$value" != *$'\r'* ]] || die 'WSS_API_KEY must be one line'
}

select_key() {
    local selected=''
    if [ -n "$CLI_KEY" ]; then
        selected=$CLI_KEY
        KEY_SOURCE='--key argument'
    elif [ "${ROTATE_KEY}" = 1 ]; then
        selected=$(generate_key)
        KEY_SOURCE='generated by --rotate-key'
    elif [ -n "${WSS_API_KEY:-}" ]; then
        selected=$WSS_API_KEY
        KEY_SOURCE='WSS_API_KEY environment variable'
    else
        selected=$(read_existing_key || true)
        if [ -n "$selected" ]; then
            KEY_SOURCE='existing environment file'
        else
            selected=$(generate_key)
            KEY_SOURCE='generated because no existing key was found'
        fi
    fi
    validate_key "$selected"
    WSS_API_KEY=$selected
    export WSS_API_KEY
}

key_fingerprint() {
    if have_command sha256sum; then
        printf '%s' "$WSS_API_KEY" | sha256sum | cut -c1-12
    else
        printf 'unavailable'
    fi
}

update_env_file() {
    local file=$1 tmp source old_key
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' RETURN

    old_key=''
    if [ -r "$file" ]; then
        old_key=$(awk -F= '$1 == "WSS_API_KEY" { print substr($0, index($0, "=") + 1); exit }' "$file")
        cat "$file" >"$tmp"
    elif [ -e "$file" ]; then
        old_key=$(run_root awk -F= '$1 == "WSS_API_KEY" { print substr($0, index($0, "=") + 1); exit }' "$file" 2>/dev/null || true)
        run_root cat "$file" >"$tmp"
    fi
    [ "$old_key" = "$WSS_API_KEY" ] || CONFIG_CHANGED=1

    source="$tmp.source"
    awk -v key="$WSS_API_KEY" '
        BEGIN { found = 0 }
        /^[[:space:]]*WSS_API_KEY=/ {
            if (!found) { print "WSS_API_KEY=" key; found = 1 }
            next
        }
        { print }
        END { if (!found) print "WSS_API_KEY=" key }
    ' "$tmp" >"$source"
    run_root install -m 600 -o "$SERVICE_USER" -g "$SERVICE_GROUP" "$source" "$file"
    rm -f "$tmp" "$source"
    trap - RETURN
}

check_paths() {
    local path
    for path in "$APP_DIR/venv/bin/python" "$APP_DIR/venv/bin/uvicorn" "$APP_DIR/venv/bin/vllm" \
        "$APP_DIR/venv/lib/python3.13/site-packages/vllm_omni/deploy/qwen3_tts.yaml" \
        "$APP_DIR/models/asr/kotoba" \
        "$APP_DIR/models/tts/qwen3" \
        "$APP_DIR/models/tts/kokoro/kokoro-v1_0.pth" \
        "$APP_DIR/models/tts/kokoro/config.json" \
        "$APP_DIR/models/tts/kokoro/voices/jf_alpha.pt" \
        "$APP_DIR/models/vad/silero/silero_vad.onnx" \
        "$APP_DIR/models/ornith/Ornith-1.5-35B-Q8_0.gguf"; do
        [ -e "$path" ] || die "required path does not exist: $path"
    done
    [ -f "$APP_DIR/tls/llm-wss.crt" ] || die "missing TLS certificate: $APP_DIR/tls/llm-wss.crt"
    [ -f "$APP_DIR/tls/llm-wss.key" ] || die "missing TLS key: $APP_DIR/tls/llm-wss.key"
}

show_status() {
    printf '%s\n' '--- system services ---'
    for unit in "${SYSTEM_UNITS[@]}"; do
        systemctl is-active "$unit" 2>/dev/null || true
        systemctl --no-pager --plain --full status "$unit" 2>/dev/null | sed -n '1,3p' || true
    done
    printf '%s\n' '--- user services ---'
    for unit in "${USER_UNITS[@]}"; do
        run_user_systemctl is-active "$unit" 2>/dev/null || true
        run_user_systemctl --no-pager --plain --full status "$unit" 2>/dev/null | sed -n '1,3p' || true
    done
    printf '%s\n' '--- listeners ---'
    ss -ltn 2>/dev/null | grep -E ':(8011|18100|18080|18444|18443)\b' || true
}

start_services() {
    run_root systemctl daemon-reload
    log "enabling and starting qwen3-tts-vllm.service"
    run_root systemctl enable --now qwen3-tts-vllm.service
    if [ "$CONFIG_CHANGED" = 1 ]; then
        log "restarting sts-ws-qwen.service to load the new key"
        run_root systemctl enable sts-ws-qwen.service
        run_root systemctl restart sts-ws-qwen.service
        log "restarting asr-ws.service to load the new key"
        run_root systemctl enable asr-ws.service
        run_root systemctl restart asr-ws.service
        log "restarting kokoro-ws.service to load the new key"
        run_root systemctl enable kokoro-ws.service
        run_root systemctl restart kokoro-ws.service
    else
        for unit in sts-ws-qwen.service asr-ws.service kokoro-ws.service; do
            log "enabling and starting $unit"
            run_root systemctl enable --now "$unit"
        done
    fi
    run_user_systemctl daemon-reload
    log "enabling and starting llama-server.service"
    run_user_systemctl enable --now llama-server.service
    log "enabling and starting llm-wss.service with its independent gateway key"
    run_user_systemctl enable --now llm-wss.service
}

ROTATE_KEY=0
STATUS_ONLY=0
DRY_RUN=0
KEY_SOURCE=''
CLI_KEY=''
CONFIG_CHANGED=0
while [ "$#" -gt 0 ]; do
    case "$1" in
        --key)
            [ "$#" -ge 2 ] || die '--key requires a value'
            CLI_KEY=$2
            shift 2
            ;;
        --key-file)
            [ "$#" -ge 2 ] || die '--key-file requires a path'
            KEY_FILE=$2
            shift 2
            ;;
        --rotate-key)
            ROTATE_KEY=1
            shift
            ;;
        --status)
            STATUS_ONLY=1
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            die "unknown option: $1"
            ;;
    esac
done

[ -d "$APP_DIR" ] || die "APP_DIR does not exist: $APP_DIR"
[ "$(id -un)" = "$SERVICE_USER" ] || die "run as $SERVICE_USER so the user systemd manager is available"

if [ "$STATUS_ONLY" = 1 ]; then
    show_status
    exit 0
fi

have_command systemctl || die 'systemctl is required'
have_command ss || log 'ss is unavailable; listener checks will be skipped'
select_key

log "selected WSS key source: $KEY_SOURCE"
log "WSS key fingerprint: $(key_fingerprint)"
check_paths

if [ "$DRY_RUN" = 1 ]; then
    log "would update adapter key files: $ASR_ENV, $WSS_ENV"
    log "would start system units: ${SYSTEM_UNITS[*]}"
    log "would start user units: ${USER_UNITS[*]}"
    exit 0
fi

update_env_file "$ASR_ENV"
update_env_file "$WSS_ENV"
run_root chmod 600 "$ASR_ENV" "$WSS_ENV"

if [ -n "${KEY_FILE:-}" ]; then
    umask 077
    printf '%s\n' "$WSS_API_KEY" >"$KEY_FILE"
    chmod 600 "$KEY_FILE"
fi

start_services
log 'all configured services started'
show_status
